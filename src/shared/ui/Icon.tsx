import {
  Battery,
  BatteryCharging,
  BatteryLow,
  Bluetooth,
  Camera,
  Check,
  CircleCheck,
  ChevronLeft,
  CircleAlert,
  Copy,
  Folder,
  History,
  Pencil,
  Plus,
  Search,
  Send,
  Settings,
  Sun,
  Square,
  Terminal,
  Trash2,
  TriangleAlert,
  Volume2,
  Headphones,
  Wifi,
  X,
  type LucideProps,
} from "lucide-react";

const icons = {
  settings: Settings,
  back: ChevronLeft,
  close: X,
  camera: Camera,
  send: Send,
  stop: Square,
  copy: Copy,
  check: Check,
  completed: CircleCheck,
  folder: Folder,
  alert: TriangleAlert,
  unavailable: CircleAlert,
  terminal: Terminal,
  plus: Plus,
  history: History,
  rename: Pencil,
  delete: Trash2,
  search: Search,
  volume: Volume2,
  brightness: Sun,
  wifi: Wifi,
  bluetooth: Bluetooth,
  headphones: Headphones,
  battery: Battery,
  batteryCharging: BatteryCharging,
  batteryLow: BatteryLow,
} as const;

export type IconName = keyof typeof icons;

export function Icon({ name, size, ...rest }: { name: IconName; size?: number } & LucideProps) {
  const Glyph = icons[name];
  return <Glyph size={size ?? 16} strokeWidth={1.7} aria-hidden focusable="false" {...rest} />;
}
