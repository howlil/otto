import {
  Camera,
  Check,
  ChevronDown,
  ChevronLeft,
  ChevronRight,
  CircleAlert,
  CircleCheck,
  CircleDot,
  Copy,
  Download,
  History,
  ListPlus,
  Mic,
  MousePointerClick,
  PanelTop,
  Pencil,
  Pin,
  Plus,
  RectangleHorizontal,
  RotateCw,
  Search,
  Send,
  Settings,
  SlidersHorizontal,
  Sparkles,
  Square,
  Terminal,
  Trash2,
  TriangleAlert,
  Volume2,
  VolumeX,
  X,
  type LucideProps,
} from "lucide-react";

const icons = {
  settings: Settings,
  back: ChevronLeft,
  chevronDown: ChevronDown,
  chevronRight: ChevronRight,
  camera: Camera,
  send: Send,
  stop: Square,
  copy: Copy,
  download: Download,
  queue: ListPlus,
  check: Check,
  completed: CircleCheck,
  alert: TriangleAlert,
  unavailable: CircleAlert,
  terminal: Terminal,
  plus: Plus,
  history: History,
  refresh: RotateCw,
  search: Search,
  close: X,
  delete: Trash2,
  rename: Pencil,
  pin: Pin,
  assistant: Sparkles,
  behavior: MousePointerClick,
  position: PanelTop,
  general: SlidersHorizontal,
  circleCompact: CircleDot,
  capsuleCompact: RectangleHorizontal,
  mic: Mic,
  volume: Volume2,
  volumeOff: VolumeX,
} as const;

export type IconName = keyof typeof icons;

export function Icon({ name, size, ...rest }: { name: IconName; size?: number } & LucideProps) {
  const Glyph = icons[name];
  return <Glyph size={size ?? 16} strokeWidth={1.7} aria-hidden focusable="false" {...rest} />;
}
